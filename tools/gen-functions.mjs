#!/usr/bin/env node
// Generate one Edge Function entry point per top-level resource.
//
// Supabase deploys a function per directory under supabase/functions, and one
// function per route would mean 48 cold starts instead of 21. Each entry point
// is a route table over the copied handlers in _routes: the handlers stay
// byte-identical to v1, and the dispatch Next used to do lives here.
//
// Generated rather than hand-written so a route added to _routes cannot be
// left unreachable. `--check` fails the build when they are out of date.

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const functions = join(root, 'supabase', 'functions')
const routesDir = join(functions, '_routes')
const check = process.argv.includes('--check')

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name === 'route.ts' ? [join(dir, e.name)] : [])
}

const METHODS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE']

// A route's URL is its directory, with Next's [param] written as :param.
const patternOf = (routePath) => {
  const dir = relative(routesDir, dirname(routePath))
  return '/' + dir.split('/').map((s) => s.replace(/^\[(.+)]$/, ':$1')).join('/')
}

const byResource = new Map()
for (const file of walk(routesDir).sort()) {
  const pattern = patternOf(file)
  const resource = pattern.split('/')[1]
  const source = readFileSync(file, 'utf8')
  const methods = METHODS.filter((m) => new RegExp(`export async function ${m}\\b`).test(source))
  if (methods.length === 0) throw new Error(`${file} exports no handler`)
  if (!byResource.has(resource)) byResource.set(resource, [])
  byResource.get(resource).push({ pattern, methods, file })
}

// One import name per route file: /workouts/:id/heats/:heatNum/complete becomes
// workouts_id_heats_heatNum_complete, so two routes cannot collide.
const aliasOf = (pattern) =>
  pattern.slice(1).replace(/[/:-]/g, '_').replace(/[^A-Za-z0-9_]/g, '') || 'root'

let wrote = 0
let stale = []
for (const [resource, routes] of [...byResource].sort()) {
  const imports = routes.map(({ pattern, methods, file }) => {
    const alias = aliasOf(pattern)
    const names = methods.map((m) => `${m} as ${alias}_${m}`).join(', ')
    return `import { ${names} } from '${'../' + relative(functions, file)}'`
  })
  const table = routes.flatMap(({ pattern, methods }) =>
    methods.map((m) => `  { method: '${m}', pattern: '${pattern}', handler: ${aliasOf(pattern)}_${m} },`))

  // The table lives beside the entry point rather than inside it so it can be
  // imported without starting a server — tools/dev-serve.ts mounts all of them
  // on one port for the parity run, and index.ts is what Supabase deploys.
  const routesFile = [
    `// Generated by tools/gen-functions.mjs. Run pnpm gen:functions after adding a route.`,
    `import { createRouter } from '../_shared/router.ts'`,
    ...imports,
    ``,
    `export const handle = createRouter('${resource}', [`,
    ...table,
    `])`,
    ``,
  ].join('\n')

  const indexFile = [
    `// Generated by tools/gen-functions.mjs. Run pnpm gen:functions after adding a route.`,
    `import { handle } from './routes.ts'`,
    ``,
    `Deno.serve(handle)`,
    ``,
  ].join('\n')

  for (const [name, body] of [['routes.ts', routesFile], ['index.ts', indexFile]]) {
    const out = join(functions, resource, name)
    if (check) {
      if (!existsSync(out) || readFileSync(out, 'utf8') !== body) stale.push(`${resource}/${name}`)
    } else {
      mkdirSync(dirname(out), { recursive: true })
      writeFileSync(out, body)
    }
  }
  wrote++
}

// One process serving every resource, for the golden-master differential.
// It mounts the same tables the deployed functions do rather than a second
// dispatch path, so what parity proves is what ships.
const names = [...byResource.keys()].sort()
const devFile = [
  `// Generated by tools/gen-functions.mjs. Run pnpm gen:functions after adding a route.`,
  ...names.map((n) => `import { handle as r_${aliasOf('/' + n)} } from '../${n}/routes.ts'`),
  ``,
  `const routers: Record<string, (req: Request) => Promise<Response>> = {`,
  ...names.map((n) => `  '${n}': r_${aliasOf('/' + n)},`),
  `}`,
  ``,
  `const port = Number(Deno.env.get('PORT') ?? '54321')`,
  ``,
  `Deno.serve({ port }, (req) => {`,
  `  const { pathname } = new URL(req.url)`,
  `  const segments = pathname.replace(/^\\/functions\\/v1/, '').split('/')`,
  `  const router = routers[segments[1]]`,
  `  if (!router) return Promise.resolve(Response.json({ error: 'Not Found' }, { status: 404 }))`,
  `  return router(req)`,
  `})`,
  ``,
].join('\n')

const devOut = join(functions, '_dev', 'serve.ts')
if (check) {
  if (!existsSync(devOut) || readFileSync(devOut, 'utf8') !== devFile) stale.push('_dev/serve.ts')
} else {
  mkdirSync(dirname(devOut), { recursive: true })
  writeFileSync(devOut, devFile)
}

// supabase/config.toml — what `supabase functions deploy` reads. Without it
// the CLI bundles each function with no import map, and every '@/lib/...'
// alias in the verbatim handlers fails to resolve on the platform. verify_jwt
// is off because the routes gate themselves and several endpoints are
// deliberately public (pinned in BACKLOG.md).
const configFile = [
  `# Generated by tools/gen-functions.mjs. Run pnpm gen:functions after adding a route.`,
  ...names.flatMap((n) => [
    ``,
    `[functions.${n}]`,
    `import_map = "./functions/deno.json"`,
    `verify_jwt = false`,
  ]),
  ``,
].join('\n')

const configOut = join(root, 'supabase', 'config.toml')
if (check) {
  if (!existsSync(configOut) || readFileSync(configOut, 'utf8') !== configFile) stale.push('../config.toml')
} else {
  writeFileSync(configOut, configFile)
}

// A resource that lost its last route leaves a function serving nothing.
const known = new Set(byResource.keys())
const orphans = readdirSync(functions, { withFileTypes: true })
  .filter((e) => e.isDirectory() && !e.name.startsWith('_') && !known.has(e.name))
  .map((e) => e.name)

if (check) {
  if (stale.length || orphans.length) {
    for (const r of stale) console.error(`stale    supabase/functions/${r}`)
    for (const r of orphans) console.error(`orphan   supabase/functions/${r} — no routes map to it`)
    console.error('\nRun pnpm gen:functions.')
    process.exit(1)
  }
  console.log(`functions: ${wrote} entry points, in sync`)
} else {
  for (const r of orphans) rmSync(join(functions, r), { recursive: true, force: true })
  console.log(`wrote ${wrote} entry points${orphans.length ? `, removed ${orphans.length} orphan(s)` : ''}`)
}
